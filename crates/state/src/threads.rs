    /// FRD-0014 R27: deletes the thread, its companion threads, their segments and activation
    /// history in one transaction; refused while any of them is open, and with `Conflict` if the
    /// thread changed since `expected_revision` (archive, rename, a new segment). Threads forked from it keep their records and lose only the
    /// lineage pointer. Native sessions are not touched.
    pub fn forget_thread_records(&self, key: &str, expected_revision: u64, at: i64) -> Result<ForgetScope> {
        id(key, CanonicalIdKind::Thread)?;
        revision(expected_revision)?;
        millis(at)?;
        self.require_writable()?;
        let mut connection = self.lock()?;
        let tx = connection.transaction_with_behavior(TransactionBehavior::Immediate)?;
        crate::schema::require_write_version(&tx)?;
        let scope = forget_scope(&tx, key)?;
        if scope.revision != expected_revision {
            return Err(ThreadError::Conflict);
        }
        for thread in &scope.thread_ids {
            tx.execute("UPDATE thread SET parent_thread_id=NULL,revision=revision+1,updated_at=max(updated_at,?2) WHERE parent_thread_id=?1", params![thread, at])?;
            tx.execute("DELETE FROM activation WHERE thread_id=?1", [thread])?;
            tx.execute("DELETE FROM segment WHERE thread_id=?1", [thread])?;
        }
        // Companions reference the worker, so they go first.
        for thread in scope.thread_ids.iter().rev() {
            tx.execute("DELETE FROM thread WHERE id=?1", [thread])?;
        }
        tx.commit()?;
        Ok(scope)
    }
    /// The undo of a New open that started nothing: the thread it created, the segment OpenCode
    /// and Pi name before their start, its membership and the workset made for it alone.
    /// Refused with `OwnedElsewhere` once any activation was recorded for the thread (a process
    /// was bound to it, even one that has ended) or another thread descends from it; nothing
    /// is changed then.
    pub fn discard_unstarted_thread(&self, key: &str) -> Result<()> {
        id(key, CanonicalIdKind::Thread)?;
        self.require_writable()?;
        let mut connection = self.lock()?;
        let tx = connection.transaction_with_behavior(TransactionBehavior::Immediate)?;
        crate::schema::require_write_version(&tx)?;
        load_thread(&tx, key)?;
        let referenced: bool = tx.query_row(
            "SELECT EXISTS(SELECT 1 FROM activation WHERE thread_id=?1) OR EXISTS(SELECT 1 FROM thread WHERE parent_thread_id=?1 OR companion_worker_thread_id=?1)",
            [key],
            |row| row.get(0),
        )?;
        if referenced {
            return Err(ThreadError::OwnedElsewhere);
        }
        crate::worksets::leave(&tx, key)?;
        tx.execute("DELETE FROM segment WHERE thread_id=?1", [key])?;
        tx.execute("DELETE FROM thread WHERE id=?1", [key])?;
        tx.commit()?;
        Ok(())
    }
    /// Attach ONLY a real adapter-provided native ID. No placeholder session is
    /// fabricated to make a launch appear resumable or available.
    pub fn attach_thread_segment(
        &self,
        record: &SegmentRecord,
        expected_thread_revision: u64,
    ) -> Result<SegmentRecord> {
        id(&record.id, CanonicalIdKind::Segment)?;
        id(&record.thread_id, CanonicalIdKind::Thread)?;
        record.native.validate().map_err(|_| ThreadError::Invalid)?;
        millis(record.created_at)?;
        revision(expected_thread_revision)?;
        if record.revision != 1
            || record.archived
            || record.ordinal == 0
            || record.harness.is_empty()
            || record.harness.len() > 64
        {
            return Err(ThreadError::Invalid);
        }
        self.require_writable()?;
        let mut connection = self.lock()?;
        let tx = connection.transaction_with_behavior(TransactionBehavior::Immediate)?;
        crate::schema::require_write_version(&tx)?;
        let thread = load_thread(&tx, &record.thread_id)?;
        if thread.archived
            || thread.revision != expected_thread_revision
            || record.created_at < thread.created_at
        {
            return Err(ThreadError::Conflict);
        }
        native_binding(&tx, record, false)?;
        let next: i64 = tx.query_row(
            "SELECT coalesce(max(ordinal),0)+1 FROM segment WHERE thread_id=?1",
            [&record.thread_id],
            |row| row.get(0),
        )?;
        if next != i64::from(record.ordinal) {
            return Err(ThreadError::Conflict);
        }
        let duplicate:bool=tx.query_row("SELECT EXISTS(SELECT 1 FROM segment WHERE id=?1 OR (store_root_id=?2 AND store_revision=?3 AND native_id=?4))",params![record.id,record.native.store_root_id,revision(record.native.store_revision)?,record.native.native_id],|row|row.get(0))?;
        if duplicate {
            return Err(ThreadError::Conflict);
        }
        tx.execute("INSERT INTO segment(id,thread_id,ordinal,harness,store_root_id,store_revision,native_id,archived,revision,created_at) VALUES(?1,?2,?3,?4,?5,?6,?7,0,1,?8)",params![record.id,record.thread_id,record.ordinal,record.harness,record.native.store_root_id,revision(record.native.store_revision)?,record.native.native_id,record.created_at])?;
        touch(&tx, &record.thread_id, record.created_at)?;
        tx.commit()?;
        Ok(record.clone())
    }
